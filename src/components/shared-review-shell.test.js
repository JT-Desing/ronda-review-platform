import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
test('team projects open the review room rather than a second project interface',()=>{
  const source=readFileSync(new URL('./SharedProjectMedia.jsx',import.meta.url),'utf8');
  assert.match(source,/setSelected\(current=>active\.assets\.some\(asset=>asset\.id===current\)\?current:active\.assets\[0\]\?\.id/);
  assert.match(source,/<SharedDeliveryGrid/);
  const grid=readFileSync(new URL('./SharedDeliveryGrid.jsx',import.meta.url),'utf8');
  assert.match(grid,/storyboard-disclosure expanded shared-delivery-controls/);
  assert.match(grid,/parrilla-disclosure-chevron/,'the disclosure affordance should show an explicit chevron');
  assert.match(grid,/parrilla-action-open/);
  assert.match(grid,/parrilla-action-closed/);
  assert.match(grid,/delivery-empty-state/);
  assert.match(grid,/assets.length>0&&<div className="storyboard-modes"/);
  assert.match(grid,/DeliveryPositionPicker/);
  assert.match(grid,/onTrash\(removing\)/);
  assert.match(grid,/onRestore\(asset\)/);
  assert.match(grid,/beginDeleteSelection\(asset\.id\)/,'the card trash action should begin multi-piece selection with that piece checked');
  assert.match(grid,/if\(selectingToDelete\)\{event\.stopPropagation\(\);toggleChecked\(asset\.id\);\}else onSelect\(asset\.id\)/,'clicking the main card toggles selection instead of opening the piece while deleting');
  assert.match(grid,/event\.target\.closest\?\.\('button,label,input,select,fieldset'\)/,'clicks on separate card controls do not toggle selection accidentally');
  assert.match(grid,/Mover a la papelera/);
  assert.match(grid,/<Icon name="trash" size=\{16\}\/>/,'bulk deletion should pair its visible action with a decorative trash icon');
  assert.match(grid,/className="delivery-asset-select"/,'each card should expose an in-place selection control');
  assert.match(grid,/delivery-selection-actions/,'selection count and delete action should appear only while selecting');
  assert.doesNotMatch(grid,/Seleccionar todas|delivery-selection-bar|delivery-select-all/,'bulk selection should not add a separate select-all banner');
  assert.match(grid,/<dialog ref=\{deleteDialog\} className="modal project-delete-dialog asset-bulk-delete-dialog"/);
  assert.match(grid,/aria-describedby="asset-delete-description"/,'the delete confirmation explains the reversible outcome to assistive technology');
  assert.match(grid,/CONFIRMAR MOVIMIENTO/,'the confirmation dialog has a clear visual eyebrow');
  assert.doesNotMatch(grid,/asset-delete-confirm/,'asset removal confirmation belongs in the modal, not the grid flow');
  const media=readFileSync(new URL('../../backend/shared-media-service.js',import.meta.url),'utf8');
  assert.match(media,/async trashAssets\(space,actor,projectId,\{assets\}\)/);
  assert.match(media,/Una o más piezas cambiaron/);
  const polish=readFileSync(new URL('./delivery-grid-polish.css',import.meta.url),'utf8');
  assert.match(polish,/animation:delivery-card-select 200ms/,'selected cards receive a subtle selection animation');
  assert.match(polish,/prefers-reduced-motion:reduce\).*li\.bulk-selected\{animation:none\}/,'selection animation respects reduced-motion preferences');
  assert.match(polish,/details\[open\]::details-content\{block-size:auto;opacity:1/,'the shared delivery disclosure should animate open');
  assert.match(polish,/prefers-reduced-motion:reduce\).*shared-delivery-controls .*transition:none/,'disclosure motion should respect reduced-motion preferences');
});
test('shared room preserves the original review shell and asset controls',()=>{
  const source=readFileSync(new URL('./SharedReviewRoom.jsx',import.meta.url),'utf8');
  assert.match(source,/className="topbar"/);
  assert.match(source,/className="asset-bar"/);
  assert.match(source,/className="social-mode-switch"/);
  assert.match(source,/OriginalMediaStage/);
  assert.doesNotMatch(source,/className="shared-review-heading"/);
});
